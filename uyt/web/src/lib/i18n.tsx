const dicts: Record<Lang, Record<Key, string>> = { ar, en };

interface I18n {
  lang: Lang;
  dir: 'rtl' | 'ltr';
  t: (k: Key) => string;
  setLang: (l: Lang) => void;
  toggle: () => void;
  /** Pick the localized field: pick(nameAr, nameEn) */
  pick: (arValue?: string | null, enValue?: string | null) => string;
}

const Ctx = createContext<I18n | null>(null);
const STORAGE = 'uyt.lang';

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE);
    if (saved === 'ar' || saved === 'en') return saved;
  } catch {
    /* ignore */
  }
  return navigator.language?.startsWith('en') ? 'en' : 'ar';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE, l);
    } catch {
      /* ignore */
    }
  }, []);
  const value = useMemo<I18n>(
    () => ({
      lang,
      dir: lang === 'ar' ? 'rtl' : 'ltr',
      t: (k) => dicts[lang][k] ?? k,
      setLang,
      toggle: () => setLang(lang === 'ar' ? 'en' : 'ar'),
      pick: (a, e) => (lang === 'en' ? e || a || '' : a || e || ''),
    }),
    [lang, setLang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('I18nProvider missing');
  return v;
}

/** For customer pages: honour the brand's default language unless the visitor picked one. */
export function useBrandDefaultLang(defaultLocale?: string) {
  const { setLang } = useI18n();
  useEffect(() => {
    let saved: string | null = null;
    try {
      saved = localStorage.getItem(STORAGE);
    } catch {
      /* ignore */
    }
    if (!saved && (defaultLocale === 'ar' || defaultLocale === 'en')) setLang(defaultLocale);
  }, [defaultLocale, setLang]);
}
